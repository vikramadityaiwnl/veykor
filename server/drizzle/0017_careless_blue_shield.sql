CREATE TABLE `agents` (
	`id` text PRIMARY KEY NOT NULL,
	`user_id` integer NOT NULL,
	`name` text DEFAULT '' NOT NULL,
	`description` text DEFAULT '' NOT NULL,
	`instructions` text DEFAULT '' NOT NULL,
	`provider_id` text DEFAULT 'muse' NOT NULL,
	`model_id` text DEFAULT '' NOT NULL,
	`reasoning_effort` text DEFAULT '' NOT NULL,
	`permission_mode` text DEFAULT 'promptUnmatched' NOT NULL,
	`project_ids` text DEFAULT '[]' NOT NULL,
	`tools_mode` text DEFAULT 'unrestricted' NOT NULL,
	`allowed_tools` text DEFAULT '[]' NOT NULL,
	`skills_mode` text DEFAULT 'unrestricted' NOT NULL,
	`skill_ids` text DEFAULT '[]' NOT NULL,
	`mcp_mode` text DEFAULT 'unrestricted' NOT NULL,
	`mcp_server_ids` text DEFAULT '[]' NOT NULL,
	`created_at` integer DEFAULT 0 NOT NULL,
	`updated_at` integer DEFAULT 0 NOT NULL,
	FOREIGN KEY (`user_id`) REFERENCES `users`(`id`) ON UPDATE no action ON DELETE no action
);
